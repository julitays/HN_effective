def _case(parts: list[str], title: str, question: str, steps: list[str], result: str, phrase: str) -> None:
    _subsection(parts, title)
    parts.append(_paragraph(f"Вопрос: {question}"))
    parts.extend(_bullet(step) for step in steps)
    parts.append(_paragraph(f"Где смотреть результат: {result}"))
    parts.append(_paragraph(f"Фраза для показа: {phrase}"))


