from __future__ import annotations

import sys
from datetime import datetime
from functools import partial
from pathlib import Path

if __package__ is None or __package__ == "":
    sys.path.append(str(Path(__file__).resolve().parents[2]))

from scripts.builders import build_page1_monthly_snapshot as page1
from scripts.builders import build_page4_tt_data as page4
from scripts.builders import build_page9_climate_data as page9
from scripts.tools.docx_utils import (
    bullet as _bullet,
    paragraph as _paragraph,
    section as _section,
    table as _docx_table,
    write_docx as _docx_write,
)


OUTPUT_DOCX = Path("docs") / "HN_BI_методология_формулы_расчетов.docx"
_table = partial(_docx_table, cell_width=2400)
_write_docx = partial(_docx_write, title="HN BI: формулы расчётов")


def _pct(value: float) -> str:
    return f"{value * 100:g}%"


def build_document() -> Path:
    parts = [
        _paragraph("HN BI: формулы расчётов", "Title"),
        _paragraph(f"Дата формирования: {datetime.now():%d.%m.%Y %H:%M}"),
    ]

    _section(parts, "1. Клиентский KPI")
    parts.extend([
        _bullet("PICOS-схема: KPI проекта = PICOS выполнение."),
        _bullet("OSA+TOP16-схема: KPI проекта = 50%×OSA выполнение + 50%×TOP16 выполнение."),
        _bullet("KPI МЕ = SUM(KPI ТТ×подтверждённые визиты МЕ) / SUM(подтверждённые визиты МЕ)."),
        _bullet("KPI региона = AVERAGE(KPI уникальных ТТ с валидным клиентским KPI)."),
    ])

    _section(parts, "2. Регион")
    parts.append(_table([["Операционный блок", "Вес"]] + [[name, _pct(weight)] for name, weight in page1.OPERATIONAL_WEIGHTS.items()]))
    parts.extend([
        _bullet("Операционная эффективность = SUM(значение×вес) / SUM(доступный вес)."),
        _bullet("Антифрод = 1−Фрод."),
        _bullet("Открытые вакансии = COUNT(вакансии, открытые на конец месяца и ещё не закрытые)."),
        _bullet("Доля вакансий = открытые вакансии МЕ / (активные МЕ + открытые вакансии МЕ)."),
        _bullet("Текучесть = уволено / (активные МЕ на конец месяца + уволено за месяц)."),
        _bullet("Доля кадрового оттока = MAX(уволено−нанято;0) / (активные МЕ на конец месяца + уволено за месяц)."),
        _bullet("Кадровая устойчивость = 1−50%×доля вакансий−30%×текучесть−20%×доля кадрового оттока."),
        _bullet("Индекс региона = SUM(компонент×вес) / SUM(доступный вес), где операционный блок =65%, кадровая устойчивость =35%."),
        _bullet("Доступность <60% → Недостаточно данных."),
        _bullet("Индекс <80%, либо 2+ жёстких сигнала, либо жёсткая текучесть+отток → Высокий риск."),
        _bullet("Индекс <88%, либо 1+ жёсткий сигнал, либо 2+ мягких сигнала → Контроль; иначе Стабильно."),
    ])
    parts.append(_table([
        ["Сигнал", "Мягкий", "Жёсткий"],
        ["KPI", "<95%", "<90%"],
        ["ОКК", "<55%", "<45%"],
        ["Обучение", "<70%", "<55%"],
        ["Фрод", ">18%", ">25%"],
        ["eNPS риск", ">=22%", ">=30%"],
        ["Вакансии", ">=12%", ">=20%"],
        ["Текучесть", ">=8%", ">=15%"],
        ["Кадровый отток", ">=3", ">=10"],
        ["Кадровая устойчивость", "<75%", "<60%"],
    ]))

    _section(parts, "3. Мерчендайзер")
    parts.append(_table([
        ["Блок", "Вес", "Зелёный", "Красный"],
        ["PICOS/OSA/TOP16", "40%", ">=99%", "<95%"],
        ["ОКК", "15%", ">=60%", "<40%"],
        ["Обучение", "20%", ">=95%", "<90%"],
        ["Аттестация клиента", "25%", ">=95%", "<90%"],
    ]))
    parts.extend([
        _bullet("Балл блока = 0, если факт < красного порога; иначе вес×MIN(факт/зелёный порог;1)."),
        _bullet("Нет аттестации клиента → +25%; остальные метрики рассчитываются."),
        _bullet("Стаж <3 месяцев → Новичок; красный блок → Зона развития; балл >=90% и все зелёные → Высокая личная готовность; иначе Соответствует роли."),
    ])

    _section(parts, "4. Сложность ТТ")
    parts.append(_table([
        ["Компонент", "Вес"],
        ["Повторяемый KPI-разрыв", _pct(page4.KPI_REPEAT_WEIGHT)],
        ["Нестабильность KPI", _pct(page4.KPI_INSTABILITY_WEIGHT)],
        ["Повторяемость ОКК", _pct(page4.OKK_REPEAT_WEIGHT)],
        ["Разрыв с похожими ТТ", _pct(page4.PEER_GAP_WEIGHT)],
        ["Смена основного МЕ", _pct(page4.ME_CHANGE_WEIGHT)],
    ]))
    parts.extend([
        _bullet("Сложность = SUM(компонент×вес) / SUM(доступный вес)."),
        _bullet("Расчёт: доступность >=60%, KPI-месяцев >=2, RTM-визитов >=3."),
        _bullet("Эталон: сложность <=25%, KPI >=95%, ОКК пусто или >=60%."),
        _bullet("Сложная ТТ: сложность >=50%; Не вина МЕ — разрыв повторён при 2+ основных МЕ."),
        _bullet("Score ТТ = 55×KPI + 45×(1−сложность)."),
    ])

    _section(parts, "5. Супервайзер — управление")
    parts.append(_table([
        ["Блок", "Вес", "Зелёный", "Красный"],
        ["KPI", "35%", "PICOS >=98%; OSA/TOP16 >=95%", "компонент <95%"],
        ["ОКК", "15%", ">=60%", "<40%"],
        ["Обучение", "15%", ">=95%", "<90%"],
        ["Фрод", "15%", "<=15%", ">20%"],
        ["Стабильность", "15%", ">=95%", "<90%"],
        ["Текучесть", "5%", "<=10%", ">15%"],
    ]))
    parts.extend([
        _bullet("Ростовая метрика: 0 ниже красного; иначе вес×MIN(факт/зелёный;1)."),
        _bullet("Обратная метрика: полный вес до зелёного; линейное снижение до 0 между зелёным и красным; 0 выше красного."),
        _bullet("Стабильность = 1−70%×вакансии−20%×текучесть−10%×чистый отток."),
        _bullet("Красный или балл <80% → Зона развития; балл >=90% без отклонений → Высокая готовность; иначе Соответствует роли."),
    ])

    _section(parts, "6. Супервайзер — личная эффективность")
    parts.append(_table([
        ["Блок", "Вес", "Зелёный", "Красный"],
        ["Аттестация клиента", "40%", ">=95%", "<90%"],
        ["Аттестация ОЭД", "20%", ">=95%", "<90%"],
        ["Продукт ОЭД", "20%", ">=95%", "<90%"],
        ["Управление ОЭД", "20%", ">=95%", "<90%"],
    ]))
    parts.extend([
        _bullet("Балл = SUM(0 или факт×вес) / SUM(доступный вес); ниже 90% блок =0."),
        _bullet("Нет ОЭД → Новичок; балл >=95%, все зелёные, класс ТОП → Высокая личная готовность; балл >=90% без красных → Соответствует роли; иначе Зона развития."),
    ])

    _section(parts, "7. Территориальный менеджер")
    parts.append(_table([
        ["Блок", "Вес", "Зелёный", "Красный"],
        ["KPI территории", "30%", "PICOS >=98%; OSA/TOP16 >=95%", "компонент <95%"],
        ["Качество команды", "20%", ">=60%", "<40%"],
        ["Обучение команды", "15%", ">=90%", "<80%"],
        ["Фрод", "15%", "<=15%", ">20%"],
        ["Стабильность", "15%", ">=95%", "<90%"],
        ["Текучесть", "5%", "<=10%", ">15%"],
    ]))
    parts.extend([
        _bullet("Цель KPI территории = SUM(цель компонента×фактический вес компонента) / SUM(вес)."),
        _bullet("Нет красных → Высокая эффективность; красный и балл <80% → Зона риска; иначе Зона развития."),
    ])

    _section(parts, "8. Адаптация новичка")
    parts.extend([
        _bullet("Разрыв с опытными = ОКК 2-го месяца − ОКК опытных региона."),
        _bullet("Операционная готовность = (I[ОКК2>=60%]+I[ОКК2>=ОКК1]+I[разрыв>=−5%]) / 3."),
        _bullet("Готовность новичка = MIN(обязательное обучение закрыто %; операционная готовность)."),
        _bullet("Вышел на уровень: обучение >=95%, ОКК2 >=60%, разрыв >=−5%."),
        _bullet("Нужна поддержка: обучение <90% или ОКК2 <50% или ОКК2 < ОКК1."),
    ])

    _section(parts, "9. Климат")
    parts.extend([
        _bullet("eNPS = (промоутеры−критики)/ответы×100."),
        _bullet("Риск ухода = ответы высокого риска / ответы с оценённым риском."),
        _bullet(f"Минимум ответов = {page9.MIN_REGION_RESPONSES}."),
        _bullet("Высокий риск: риск >=24% или удовлетворённость <55%."),
        _bullet("Контроль: риск >=18% или удовлетворённость <63%; иначе Стабильно."),
    ])

    _write_docx(parts, OUTPUT_DOCX)
    return OUTPUT_DOCX


def main() -> None:
    print(f"Сформировано: {build_document()}")


if __name__ == "__main__":
    main()
