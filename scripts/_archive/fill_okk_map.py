updated_name = 0
updated_take = 0
updated_short = 0

for i, row in df.iterrows():
    short = str(row.get("Сокращение в файле", "")).strip()
    full  = str(row.get("Полное название", "")).strip()

    # Заполняем строки 73-82 — подставляем Сокращение в файле
    if pd.isna(row.get("Сокращение в файле")) and full in FULL_TO_SHORT:
        df.at[i, "Сокращение в файле"] = FULL_TO_SHORT[full]
        short = FULL_TO_SHORT[full]
        updated_short += 1

    if short not in FILL:
        continue

    desired_name, take = FILL[short]

    # Заполняем только если ячейка пустая
    if pd.isna(row.get("Необходимое название в файле")):
        df.at[i, "Необходимое название в файле"] = desired_name
        updated_name += 1

    if pd.isna(row.get("Берем в витрину или нет")):
        df.at[i, "Берем в витрину или нет"] = take
        updated_take += 1

df.to_excel("okk_columns_map.xlsx", index=False)
print(f"Обновлено названий:    {updated_name}")
print(f"Обновлено 'берём':     {updated_take}")
print(f"Заполнено сокращений:  {updated_short}")
print(f"Сохранено: okk_columns_map.xlsx")
